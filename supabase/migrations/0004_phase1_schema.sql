-- ============================================================================
-- Migration 0004: Phase 1 schema additions
-- ============================================================================
-- Adds the tables and columns the Phase 1 design needs: contact history,
-- the Appendix D required-documents checklist, the alerts model, going-rate
-- reference data, bank holidays for working-day maths, attendance, per-period
-- pay records, role-eligibility reviews, settings, and the statutory excuse
-- and retention fields on existing tables.
-- Run after 0003_seed.sql.
-- ============================================================================

-- --- New enums --------------------------------------------------------------
create type excuse_type as enum ('continuous', 'time_limited', 'six_month', 'none');
create type doc_status as enum ('present', 'missing', 'expiring', 'expired');
create type retention_basis as enum ('appendix_d', 'rtw_employment_plus_2yr', 'other');
create type alert_type as enum (
  'visa_expiry', 'rtw_follow_up', 'dbs_renewal', 'document_expiry',
  'reporting_deadline', 'review_due', 'sms_login_stale', 'salary_shortfall',
  'role_review_due', 'unexplained_absence'
);
create type alert_severity as enum ('info', 'amber', 'red');
create type alert_status as enum ('open', 'acknowledged', 'resolved', 'dismissed');
create type attendance_status as enum ('present', 'absent_authorised', 'absent_unauthorised', 'remote');

-- --- Alterations to existing tables -----------------------------------------
-- Right to work: statutory excuse model (List A / List B of the RTW guide)
alter table right_to_work_checks
  add column if not exists excuse_type excuse_type not null default 'none',
  add column if not exists excuse_expiry date;

-- Documents: which retention clock applies (Appendix D vs RTW employment+2yr)
alter table documents
  add column if not exists retention_basis retention_basis not null default 'appendix_d',
  add column if not exists review_status doc_status not null default 'present';

-- ============================================================================
-- contact_history: Appendix D requires a HISTORY of address, email, phone
-- ============================================================================
create table contact_history (
  id            uuid primary key default gen_random_uuid(),
  worker_id     uuid not null references workers(id) on delete cascade,
  field         text not null,          -- 'address' | 'email' | 'phone'
  value         text not null,
  effective_from date not null default current_date,
  effective_to  date,                   -- null = current value
  created_at    timestamptz not null default now()
);
create index idx_contact_history_worker on contact_history(worker_id);

-- ============================================================================
-- required_documents: the Appendix D checklist per worker
-- ============================================================================
create table required_documents (
  id            uuid primary key default gen_random_uuid(),
  worker_id     uuid not null references workers(id) on delete cascade,
  doc_key       text not null,          -- e.g. 'right_to_work','payslips','job_description'
  label         text not null,
  required      boolean not null default true,
  status        doc_status not null default 'missing',
  document_id   uuid references documents(id) on delete set null,
  expiry_date   date,
  review_date   date,
  notes         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (worker_id, doc_key)
);
create index idx_reqdocs_worker on required_documents(worker_id);
create trigger trg_reqdocs_updated before update on required_documents
  for each row execute function set_updated_at();

-- ============================================================================
-- alerts: generated by the nightly engine, shown in-app and emailed
-- ============================================================================
create table alerts (
  id            uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references organisation(id) on delete cascade,
  worker_id     uuid references workers(id) on delete cascade,
  alert_type    alert_type not null,
  severity      alert_severity not null default 'amber',
  status        alert_status not null default 'open',
  title         text not null,
  detail        text,
  due_date      date,
  days_out      integer,                -- days until due at time of raising
  resolved_at   timestamptz,
  resolved_by   uuid references app_users(id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index idx_alerts_org_status on alerts(organisation_id, status);
create index idx_alerts_worker on alerts(worker_id);
create index idx_alerts_due on alerts(due_date);
create trigger trg_alerts_updated before update on alerts
  for each row execute function set_updated_at();

-- ============================================================================
-- soc_going_rates: reference data for CoS salary validation (editable)
-- ============================================================================
create table soc_going_rates (
  id            uuid primary key default gen_random_uuid(),
  soc_code      text not null unique,
  occupation    text not null,
  going_rate_annual numeric(12,2),      -- standard going rate
  hourly_rate   numeric(8,2),
  effective_from date,
  source_note   text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create trigger trg_sgr_updated before update on soc_going_rates
  for each row execute function set_updated_at();

-- ============================================================================
-- bank_holidays: England & Wales, for working-day deadline maths
-- ============================================================================
create table bank_holidays (
  holiday_date  date primary key,
  title         text
);

-- ============================================================================
-- attendance: distinct from absence; supports unexplained-absence detection
-- ============================================================================
create table attendance (
  id            uuid primary key default gen_random_uuid(),
  worker_id     uuid not null references workers(id) on delete cascade,
  on_date       date not null,
  status        attendance_status not null,
  note          text,
  created_at    timestamptz not null default now(),
  unique (worker_id, on_date)
);
create index idx_attendance_worker on attendance(worker_id);

-- ============================================================================
-- pay_periods: per-period salary compliance; figures sourced from FreeAgent
-- ============================================================================
create table pay_periods (
  id            uuid primary key default gen_random_uuid(),
  worker_id     uuid not null references workers(id) on delete cascade,
  period_start  date not null,
  period_end    date not null,
  gross_paid    numeric(12,2),
  hours         numeric(7,2),
  payslip_document_id uuid references documents(id) on delete set null,
  meets_going_rate boolean,
  shortfall     numeric(12,2),
  source        text default 'freeagent_manual',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint chk_pay_dates check (period_end >= period_start)
);
create index idx_pay_worker on pay_periods(worker_id);
create trigger trg_pay_updated before update on pay_periods
  for each row execute function set_updated_at();

-- ============================================================================
-- role_eligibility_reviews: periodic check the role still qualifies
-- ============================================================================
create table role_eligibility_reviews (
  id            uuid primary key default gen_random_uuid(),
  worker_id     uuid not null references workers(id) on delete cascade,
  reviewed_on   date not null default current_date,
  reviewed_by   text,
  still_eligible boolean,
  next_review_due date,
  notes         text,
  created_at    timestamptz not null default now()
);
create index idx_role_review_worker on role_eligibility_reviews(worker_id);

-- ============================================================================
-- settings: single-row configurable thresholds and rules
-- ============================================================================
create table settings (
  id              uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references organisation(id) on delete cascade,
  alert_offsets   integer[] not null default '{90,60,30,7}',
  report_standard_days integer not null default 10,
  report_org_days integer not null default 20,
  sms_login_stale_months integer not null default 10,
  rtw_retention_years integer not null default 2,
  updated_at      timestamptz not null default now(),
  unique (organisation_id)
);
create trigger trg_settings_updated before update on settings
  for each row execute function set_updated_at();

