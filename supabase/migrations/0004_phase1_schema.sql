-- --- Grants for the Data API ------------------------------------------------
-- Auto-expose is off (the safer setting), so grant the new tables to the
-- signed-in role and set defaults so future tables are covered too.
-- Row Level Security still governs what each user can actually see.
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;
alter default privileges in schema public
  grant select, insert, update, delete on tables to authenticated;
